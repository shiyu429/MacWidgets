    /// <summary>按查询匹配本地城市。精确匹配（含去后缀/补「市」）优先于前缀；同名前缀再比名称长度。</summary>
    public static List<GeoPlace> SearchLocal(string rawQuery, int limit = 12)
    {
        string raw = (rawQuery ?? "").Trim();
        if (raw.Length == 0) return [];
        string norm = WeatherClient.NormalizeCityQuery(raw);
        var scored = new List<(GeoPlace place, double score)>();
        foreach (var e in All)
        {
            string name = e.Name;
            string nameNorm = WeatherClient.NormalizeCityQuery(name);
            string withShi = nameNorm.EndsWith("市", StringComparison.Ordinal) ? nameNorm : nameNorm + "市";
            double score = 0;
            if (name.Equals(raw, StringComparison.OrdinalIgnoreCase) ||
                nameNorm.Equals(norm, StringComparison.OrdinalIgnoreCase) ||
                withShi.Equals(raw, StringComparison.OrdinalIgnoreCase) ||
                withShi.Equals(norm + "市", StringComparison.OrdinalIgnoreCase))
                score = 2000;
            else if (norm.Length > 0 && (nameNorm.StartsWith(norm, StringComparison.OrdinalIgnoreCase) ||
                                          withShi.StartsWith(norm, StringComparison.OrdinalIgnoreCase)))
                score = 1200 - (nameNorm.Length - norm.Length) * 5;
            else if (norm.Length >= 2 && nameNorm.Contains(norm, StringComparison.OrdinalIgnoreCase))
                score = 400;
            else
                continue;
            // 展示名：常用简称补「市」（直辖市/港澳/已带市除外）
            string display = DisplayName(name);
            scored.Add((new GeoPlace(display, e.Province, display, "中国", e.Lat, e.Lon, "PPLA", 1_000_000), score));
        }
        return scored
            .OrderByDescending(x => x.score)
            .ThenBy(x => x.place.Name, StringComparer.Ordinal)
            .Select(x => x.place)
            .Take(Math.Max(1, limit))
            .ToList();
    }

    public static string DisplayName(string name)
    {
        if (string.IsNullOrEmpty(name)) return name;
        if (name is "北京" or "上海" or "天津" or "重庆") return name + "市";
        if (name is "香港" or "澳门" or "台湾") return name;
        if (name.EndsWith("市", StringComparison.Ordinal) ||
            name.EndsWith("州", StringComparison.Ordinal) ||
            name.EndsWith("盟", StringComparison.Ordinal) ||
            name.EndsWith("地区", StringComparison.Ordinal))
            return name;
        return name + "市";
    }
